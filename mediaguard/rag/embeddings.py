"""Embedding generation for RAG system.

Two interchangeable backends for the same all-MiniLM-L6-v2 model (384-d):
- "sentence-transformers" (default): runs the model in-process.
- "ollama": calls a local Ollama server (`ollama pull all-minilm`), which avoids
  installing PyTorch. Select it with EMBEDDING_BACKEND=ollama.
"""

import json
import os
import urllib.request
from typing import List


class EmbeddingGenerator:
    """Generates embeddings for text using sentence transformers or Ollama."""

    def __init__(self, model_name: str = "all-MiniLM-L6-v2", backend: str = None):
        """Initialize the embedding generator.

        Args:
            model_name: Name of the sentence transformer model to use
            backend: "sentence-transformers" or "ollama" (defaults to EMBEDDING_BACKEND env var)
        """
        self.backend = (backend or os.getenv("EMBEDDING_BACKEND", "sentence-transformers")).lower()
        self.model_name = model_name

        if self.backend == "ollama":
            self.ollama_url = os.getenv("OLLAMA_BASE_URL", "http://localhost:11434").rstrip("/")
            self.ollama_model = os.getenv("OLLAMA_EMBED_MODEL", "all-minilm")
            self.model = None
        else:
            # Imported lazily so the Ollama backend works without PyTorch installed.
            from sentence_transformers import SentenceTransformer
            self.model = SentenceTransformer(model_name)

    def _ollama_embed(self, texts: List[str]) -> List[List[float]]:
        body = json.dumps({"model": self.ollama_model, "input": texts}).encode()
        req = urllib.request.Request(f"{self.ollama_url}/api/embed", data=body,
                                     headers={"Content-Type": "application/json"})
        with urllib.request.urlopen(req, timeout=60) as resp:
            return json.loads(resp.read())["embeddings"]

    def generate_embedding(self, text: str) -> List[float]:
        """Generate embedding for a single text.

        Args:
            text: Text to generate embedding for

        Returns:
            List of floats representing the embedding vector
        """
        if self.backend == "ollama":
            return self._ollama_embed([text])[0]
        embedding = self.model.encode(text, convert_to_numpy=True)
        return embedding.tolist()

    def generate_embeddings(self, texts: List[str]) -> List[List[float]]:
        """Generate embeddings for multiple texts.

        Args:
            texts: List of texts to generate embeddings for

        Returns:
            List of embedding vectors
        """
        if self.backend == "ollama":
            return self._ollama_embed(list(texts))
        embeddings = self.model.encode(texts, convert_to_numpy=True)
        return embeddings.tolist()

    def get_embedding_dimension(self) -> int:
        """Get the dimension of embeddings generated by this model.

        Returns:
            Dimension of the embedding vectors
        """
        # Test with a dummy text
        test_embedding = self.generate_embedding("test")
        return len(test_embedding)
